// Development-only generator. Run: node src/io/generateRuntimeSchema.mjs
// TypeScript is already a devDependency; no compiler ships with the application.
import ts from 'typescript'
import fs from 'node:fs'
const paths = ['src/model/types.ts']
const program = ts.createProgram(paths, { strictNullChecks: true, target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler })
const checker = program.getTypeChecker()
const definitions = {}
const seen = new Map()
function shape(type) {
  const f = type.flags
  if (f & ts.TypeFlags.Undefined) return { type: 'undefined' }
  if (f & ts.TypeFlags.Null) return { literal: null }
  if (f & ts.TypeFlags.StringLiteral || f & ts.TypeFlags.NumberLiteral) return { literal: type.value }
  if (f & ts.TypeFlags.BooleanLiteral) return { literal: type.intrinsicName === 'true' }
  if (f & ts.TypeFlags.String) return { type: 'string' }
  if (f & ts.TypeFlags.Number) return { type: 'number' }
  if (f & ts.TypeFlags.Boolean) return { type: 'boolean' }
  if (type.isUnion()) return { union: type.types.map(shape) }
  if (checker.isTupleType(type)) return { tuple: checker.getTypeArguments(type).map(shape) }
  if (checker.isArrayType(type)) return { array: shape(checker.getTypeArguments(type)[0]) }
  if (!(f & ts.TypeFlags.Object)) throw new Error(`Unsupported: ${checker.typeToString(type)}`)
  if (seen.has(type)) return { ref: seen.get(type) }
  let name = type.aliasSymbol?.name ?? type.symbol?.name
  if (!name || name === '__type' || definitions[name]) name = `Object${seen.size}`
  seen.set(type, name)
  definitions[name] = null
  const properties = {}
  for (const p of checker.getPropertiesOfType(type)) {
    properties[p.name] = { shape: shape(checker.getTypeOfSymbolAtLocation(p, p.valueDeclaration ?? p.declarations[0])), ...(p.flags & ts.SymbolFlags.Optional ? { optional: true } : {}) }
  }
  const index = checker.getIndexTypeOfType(type, ts.IndexKind.String)
  definitions[name] = { properties, ...(index ? { values: shape(index) } : {}) }
  return { ref: name }
}
for (const [i, name] of [[0, 'Scenario'], [0, 'SpecModel']]) {
  const declaration = program.getSourceFile(paths[i]).statements.find(n => n.name?.text === name)
  shape(checker.getTypeAtLocation(declaration))
}
// One JSON string instead of a nested object literal: the descriptors are pure data and
// JSON.parse builds them about three times faster than the equivalent literal, on the
// startup path before first paint. Backslashes first, then the quote that delimits it.
const literal = JSON.stringify(definitions).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
const out = '// Generated by generateRuntimeSchema.mjs from the Board domain types.\n// Do not hand-edit: runtimeValidation.ts adds compatibility and semantic rules.\nimport type { RuntimeShape } from \'./runtimeValidation\'\n\n// Emitted as JSON: it parses faster than the same object literal at startup.\nexport const runtimeShapes = JSON.parse(\n  \'' + literal + '\',\n) as Record<string, RuntimeShape>\n'
if (process.argv.includes('--check')) {
  if (fs.readFileSync('src/io/runtimeSchema.ts', 'utf8') !== out) throw new Error('Runtime shape descriptors are stale; regenerate and review compatibility.')
} else fs.writeFileSync('src/io/runtimeSchema.ts', out)
